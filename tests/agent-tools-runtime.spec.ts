import { describe, expect, it, vi } from 'vitest';
import { db } from '@/lib/db';
import { sanitizeInternalNoteContent, formatTeamBusinessHours } from '@/services/agent-tools/runtime';

describe('agent tools runtime', () => {
  it('compacts oversized internal notes generated by the AI', () => {
    const noisyNote = [
      'Cliente relatou perda de sinal LOS e esta validando o cabo interno.',
      'Proximo passo: aguardar retorno sobre a luz LOS e conexao fisica do cabo.',
      'Registro concluido com sucesso pelo agente IA persona Lucas analista N2 Suporte Velpro Telecom.',
      'Fim da nota interna tecnica de acompanhamento operacional do ticket para historico de atendimento e auditoria.',
      'Lucas Suporte N2 finaliza a nota agora.',
    ].join(' '.repeat(30));

    const sanitized = sanitizeInternalNoteContent(noisyNote);

    expect(sanitized.length).toBeLessThanOrEqual(500);
    expect(sanitized).toContain('Cliente relatou perda de sinal LOS');
    expect(sanitized).not.toMatch(/Registro concluido|Fim da nota|finaliza a nota/i);
  });

  describe('formatTeamBusinessHours', () => {
    it('returns default fallback when no business hours exist', async () => {
      vi.spyOn(db, 'query').mockResolvedValueOnce({ rows: [] } as any);
      const res = await formatTeamBusinessHours('team-123');
      expect(res).toBe('horário comercial');
    });

    it('formats consecutive days with same schedule correctly', async () => {
      const mockRows = [
        { day_of_week: 'Segunda-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Terça-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Quarta-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Quinta-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Sexta-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
      ];
      vi.spyOn(db, 'query').mockResolvedValueOnce({ rows: mockRows } as any);
      const res = await formatTeamBusinessHours('team-123');
      expect(res).toBe('Segunda a Sexta das 08:00 às 18:00');
    });

    it('formats complex multiple schedules beautifully', async () => {
      const mockRows = [
        { day_of_week: 'Segunda-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Terça-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Quarta-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Quinta-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Sexta-feira', is_enabled: true, start_time: '08:00', end_time: '18:00' },
        { day_of_week: 'Sábado', is_enabled: true, start_time: '08:00', end_time: '12:00' },
      ];
      vi.spyOn(db, 'query').mockResolvedValueOnce({ rows: mockRows } as any);
      const res = await formatTeamBusinessHours('team-123');
      // The result should contains both schedules mapped beautifully
      expect(res).toContain('Segunda a Sexta das 08:00 às 18:00');
      expect(res).toContain('Sábado das 08:00 às 12:00');
    });
  });
});
