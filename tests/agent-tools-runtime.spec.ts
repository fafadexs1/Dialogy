import { describe, expect, it } from 'vitest';

import { sanitizeInternalNoteContent } from '@/services/agent-tools/runtime';

describe('agent tools runtime', () => {
  it('compacts oversized internal notes generated by the AI', () => {
    const noisyNote = [
      'Cliente relatou perda de sinal LOS e esta validando o cabo interno.',
      'Proximo passo: aguardar retorno sobre a luz LOS e conexao fisica do cabo.',
      'Registro concluido com sucesso pelo agente IA persona Lucas analista N2 Suporte Velpro Telecom.',
      'Fim da nota interna tecnica de acompanhamento operacional do ticket para historico de atendimento e auditoria.',
      'Lucas Suporte N2 finaliza a nota agora.',
    ].join(' '.repeat(30));

    const sanitized = sanitizeInternalNoteContent(noisyNote);

    expect(sanitized.length).toBeLessThanOrEqual(500);
    expect(sanitized).toContain('Cliente relatou perda de sinal LOS');
    expect(sanitized).not.toMatch(/Registro concluido|Fim da nota|finaliza a nota/i);
  });
});
